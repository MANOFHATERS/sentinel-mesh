    def test_lower_separability_makes_the_problem_harder(self):
        """Guards against the generator drifting toward trivially separable data."""
        def auc_at(separability: float) -> float:
            normalizer = CICIDS2017Normalizer(tenant_id="acme", strict=True)
            enricher = SessionContextEnricher()
            alerts = [
                enricher.enrich(normalizer.normalize(row, row_index=i))
                for i, row in enumerate(
                    SyntheticCICGenerator(
                        seed=SEED, separability=separability
                    ).rows(5000)
                )
            ]
            y = np.array(
                [0 if a.ground_truth_label == "benign" else 1 for a in alerts], dtype=int
            )
            split = three_way_split(y, seed=SEED)
            train = [alerts[i] for i in split.train_benign]
            vectorizer = AlertVectorizer().fit(train)
            ensemble = build_default_ensemble(random_state=SEED).fit(
                vectorizer.transform(train)
            )
            return roc_auc(
                y[split.test], ensemble.score(vectorizer.transform([alerts[i] for i in split.test]))
            )

        assert auc_at(0.25) < auc_at(1.0)
