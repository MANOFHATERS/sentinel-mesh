class TestCrossDatasetHarmonization:
    def test_both_generators_flow_through_their_own_normalizers(self):
        cic_normalizer = CICIDS2017Normalizer(tenant_id="acme", strict=True)
        unsw_normalizer = UNSWNB15Normalizer(tenant_id="acme", strict=True)
        cic = [
            cic_normalizer.normalize(row, row_index=index)
            for index, row in enumerate(SyntheticCICGenerator(seed=1).rows(500))
        ]
        unsw = [
            unsw_normalizer.normalize(row, row_index=index)
            for index, row in enumerate(SyntheticUNSWGenerator(seed=1).rows(500))
        ]
        assert all(a is not None for a in cic)
        assert all(a is not None for a in unsw)
        assert cic_normalizer.report.rows_rejected == 0
        assert unsw_normalizer.report.rows_rejected == 0

    def test_a_model_fitted_on_one_can_score_the_other(self):
        """The harmonization contract: one vectorizer, two source schemas."""
        cic_normalizer = CICIDS2017Normalizer(tenant_id="acme", strict=True)
        unsw_normalizer = UNSWNB15Normalizer(tenant_id="acme", strict=True)
        enricher_a, enricher_b = SessionContextEnricher(), SessionContextEnricher()

        cic = [
            enricher_a.enrich(cic_normalizer.normalize(row, row_index=i))
            for i, row in enumerate(SyntheticCICGenerator(seed=1).rows(3000))
        ]
        unsw = [
            enricher_b.enrich(unsw_normalizer.normalize(row, row_index=i))
            for i, row in enumerate(SyntheticUNSWGenerator(seed=2).rows(3000))
        ]

        benign = [a for a in cic if a.ground_truth_label == "benign"]
        vectorizer = AlertVectorizer().fit(benign)
        ensemble = build_default_ensemble(random_state=SEED).fit(vectorizer.transform(benign))

        y_unsw = np.array(
            [0 if a.ground_truth_label == "benign" else 1 for a in unsw], dtype=int
        )
        auc = roc_auc(y_unsw, ensemble.score(vectorizer.transform(unsw)))
        assert auc >= 0.80, f"cross-schema scoring collapsed to {auc:.4f}"

    def test_the_two_corpora_use_different_address_space(self):
        # If the generators shared addresses, the enricher's window features would
        # correlate across corpora and the cross-dataset test would be self-fulfilling.
        cic_normalizer = CICIDS2017Normalizer(tenant_id="acme", strict=True)
        unsw_normalizer = UNSWNB15Normalizer(tenant_id="acme", strict=True)
        cic_ips = {
            cic_normalizer.normalize(row, row_index=i).src_ip
            for i, row in enumerate(SyntheticCICGenerator(seed=1).rows(300))
        }
        unsw_ips = {
            unsw_normalizer.normalize(row, row_index=i).src_ip
            for i, row in enumerate(SyntheticUNSWGenerator(seed=1).rows(300))
        }
        assert cic_ips & unsw_ips == set()


class TestGeneratorRealism:
    def test_flow_level_class_balance_matches_the_request(self):
        """Campaign bursts changed the sampling unit; the solved probabilities fix it.

        Tolerance is wide on purpose: a single recon campaign can emit 1,200 flows,
        so at 20,000 flows the benign share genuinely fluctuates by several points.
        That variance is realistic — CIC-IDS2017's port scan is one afternoon of one
        day — and a tight bound here would be a flaky test asserting a false precision.
        """
        from collections import Counter

        normalizer = CICIDS2017Normalizer(tenant_id="acme", strict=True)
        families = Counter(
            normalizer.normalize(row, row_index=i).ground_truth_label
            for i, row in enumerate(
                SyntheticCICGenerator(seed=5, benign_fraction=0.80).rows(20_000)
            )
        )
        benign_share = families["benign"] / sum(families.values())
        assert 0.70 <= benign_share <= 0.92, f"benign flow share {benign_share:.3f}"

    def test_attacks_arrive_as_time_contiguous_campaigns(self):
        # Scattered attacks would be undetectable by anything a real SOC uses.
        normalizer = CICIDS2017Normalizer(tenant_id="acme", strict=True)
        alerts = [
            normalizer.normalize(row, row_index=i)
            for i, row in enumerate(SyntheticCICGenerator(seed=6).rows(4000))
        ]
        attack_runs = 0
        previous_was_attack = False
        for alert in alerts:
            is_attack = alert.ground_truth_label != "benign"
            if is_attack and not previous_was_attack:
                attack_runs += 1
            previous_was_attack = is_attack
        attacks = sum(1 for a in alerts if a.ground_truth_label != "benign")
        if attacks:
            # Long runs, not a scatter: mean run length well above 1.
            assert attacks / attack_runs > 10.0

    def test_timestamps_are_monotonic(self):
        # The causal enricher depends on it, so the generator must not go backwards.
        normalizer = CICIDS2017Normalizer(tenant_id="acme", strict=True)
        times = [
            normalizer.normalize(row, row_index=i).timestamp
            for i, row in enumerate(SyntheticCICGenerator(seed=7).rows(2000))
        ]
        assert times == sorted(times)

